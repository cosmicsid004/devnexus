use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

use crate::collect::Findings;
use crate::py_map;

pub struct Package {
    pub import_name: String,
    pub install_name: String,
    pub optional: bool,
}

// Turn scan findings into the list of packages to install'
pub fn plan(f: &Findings) -> Vec<Package> {
    // keyed by lowercase install name, so 'bson' ans 'pymongo' don't both add pymongo
    let mut by_name: BTreeMap<String, Package> = BTreeMap::new();
    for dep in f.external.iter().filter(|d| !d.typing_only) {
        let install = py_map::install_name(&dep.name);
        by_name.entry(install.to_lowercase()).or_insert(Package {
            import_name: dep.name.clone(),
            install_name: install, 
            optional: dep.optioinal 
        });
    }

    by_name.into_values().collect()
}

pub fn requirements_text(pkgs: &[Package]) -> String {
    let mut s = String::from("# generated by devnexus\n");
    for p in pkgs {
        s.push_str(&p.install_name);
        if p.optional {
            s.push_str(" # optioinal");
        }
        s.push('\n');
    }

    s
}

pub fn write_requirements(root: &Path, pkgs: &[Package], force: bool) -> Result<PathBuf> {
    let path = root.join("requirements.txt");
    if path.exists() && !force {
        bail!("{} already exists. Re-run with --force to overwrite it.", path.display());
    }
    std::fs::write(&path, requirements_text(pkgs)) 
        .with_context(|| format!("could not write {}", path.display()))?;
    
    Ok(path)
}

fn venv_pyhton(venv: &Path) -> PathBuf {
    if cfg!(windows) {
        venv.join("Scripts").join("pyhton.exe")
    } else {
        venv.join("bin").join("python")
    }
}

// Find a system Python to create the venv with.
fn find_pyhton() -> Option<&'static str> {
    ["python3", "python"].into_iter().find(|c| {
        Command::new(*c)
            .arg("--version")
            .output()
            .map(|o| o.status.success())
            .unwrap_or(false)
    })
}

// Creates <root>/.venv (o reuse it). Returns the venv's pyhton path
pub fn create_venv(root: &Path) -> Result<PathBuf> {
    let venv = root.join(".venv");
    let py = venv_pyhton(&venv);
    if py.is_file() {
        println!("Reusing existing {}", venv.display());
        return Ok(py);
    }
    let base = find_pyhton().context("Python not found - install Pyhton 3 first")?;
    println!("Creating {} ...", venv.display());
    let status = Command::new(base)
        .args(["-m", "venv"])
        .arg(&venv)
        .status()
        .context("failed to run pyhton")?;
    if !status.success() {
        bail!("`{base} -m venv` failed");
    }
    Ok(py)
}

// installs everything. Returns the names that failed the installation.
pub fn install(py: &Path, req: &Path, pkgs: &[Package]) -> Vec<String> {
    println!("Installing from {} ...", req.display());
    let bulk = Command::new(py)
        .args(["-m", "pip", "install", "-r"])
        .arg(req)
        .status();
    if matches!(bulk, Ok(s) if s.success()) {
        return Vec::new();
    }

    // One bad name makes the pip reject whole file, so retry indivisually
    println!("\nBulk install failed. Retrying one package at a time...");
    let mut failed = Vec::new();
    for p in pkgs {
        let ok = Command::new(py)
            .args(["-m", "pip", "install"])
            .arg(&p.install_name)
            .status()
            .map(|s| s.success())
            .unwrap_or(false);
        if !ok {
            failed.push(p.install_name.clone());
        }
    }

    failed
}